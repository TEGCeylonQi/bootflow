//! 诊断码。
//!
//! **产地**：所有诊断码在这里定义，`diag/*` 负责产生，`advise` 负责消费。
//! 这个方向不能反——码是"我们查出了什么"的名字，它的名字应该由发现它的
//! 那一层决定，而不是由解释它的那一层决定。
//!
//! ## 命名规则
//!
//! - 全大写下划线，描述**事实**而不是**处置**。
//!   `SLOW_START`（它启动慢）而不是 `SHOULD_DISABLE`（你该关掉它）。
//!   事实是稳定的，处置会随版本变；把处置编进码里，将来改措辞就得改码，
//!   而码一旦出现在导出的报告里就不能轻易改了。
//! - 每个码只能有一个严重级别的默认值，实际级别可在产生处覆盖。

/* ───────────── 开机耗时（来自系统事件日志） ───────────── */

/// 命中 Event 103：系统记录了它上次开机启动很慢。**实测数据**。
pub const SLOW_START: &str = "SLOW_START";

/// 命中 WDI 的「高启动影响」档。**实测数据，且尺子来自微软**。
///
/// 与 `SLOW_START` 分开是有理由的：后者是"它自己启动得慢"，
/// 前者是"它占了开机期间大量 CPU 或磁盘"——一个后台同步工具
/// 可以启动得飞快，然后在登录后把磁盘读满。处置方向也不同：
/// 前者该考虑延迟启动，后者该考虑干脆别让它自启。
///
/// 只在高档产出，不产出中/低档：阈值已经是微软筛过一遍的，
/// 我们再自己加一层"是否值得提示"的判断只会让两边口径打架。
pub const HIGH_STARTUP_IMPACT: &str = "HIGH_STARTUP_IMPACT";

/* ───────────── 状态与出厂预期不符 ───────────── */

/// 服务的启动类型被改成了手动/禁用，但它出厂默认是自动。
///
/// 典型：`ClickToRunSvc` 被"优化"成手动，代价是 Office 首次打开卡顿。
pub const MANUAL_BUT_SHOULD_AUTO: &str = "MANUAL_BUT_SHOULD_AUTO";

/// Office 的后台任务被整体关闭。
///
/// 与上一条**语义不同**：这个状态很可能是用户有意为之，
/// 所以措辞是"说明代价"而不是"建议修复"。
pub const OFFICE_TASKS_DISABLED: &str = "OFFICE_TASKS_DISABLED";

/* ───────────── 系统注入 ───────────── */

/// 全局注入项：代码被加载进其它进程，而不是自己启动。
///
/// 典型：`AppInit_DLLs`（MacType 字体注入走的就是它）。
pub const GLOBAL_HOOK: &str = "GLOBAL_HOOK";

/// `IFEO` 劫持：某个程序的启动被重定向或附加了参数。
///
/// 正当用途（调试器、优先级调整）与恶意用途都用这一个机制，
/// 所以措辞必须是"说明这里有一处改写"而不是"发现病毒"。
pub const IFEO_HIJACK: &str = "IFEO_HIJACK";

/// 程序启动被附加了优先级改写。
///
/// 与 `IFEO_HIJACK` 分开，是因为后果完全不同：前者可能让程序根本起不来，
/// 后者是"它跑起来之后抢资源"，而且**其中 `RealTime` 档会引发音频爆音
/// 与系统假死**——那是需要单独提醒的一档。
pub const IFEO_PRIORITY: &str = "IFEO_PRIORITY";

/// 注入配置已登记，但注入开关是关的。
///
/// 本机实测：`AppInit_DLLs` 里有值，而 `LoadAppInit_DLLs = 0`。
/// 少见但真实的情况——DLL 名字还留在注册表里，注入实际早就不生效了。
/// 把它当"发现全局注入"报出来是**误报**，而且会让用户白紧张一场。
/// 所以单独一个码，如实说"配置在、开关关着"。
pub const HOOK_NOT_ACTIVE: &str = "HOOK_NOT_ACTIVE";

/* ───────────── 签名与来源 ───────────── */

// 「无法核验发布者」**刻意没有诊断码**。
//
// 它是一个持续存在的属性，而不是某次检查发现的问题：属性面板的签名区块
// 已经在展示发布者与校验结果，风险评级也把它算进了理由里。
// 再挂一个诊断码，只会在同一屏里把同一件事说三遍。
// 这也符合原本的约定：码只用于"事实与预期不符"的那类发现。

/* ───────────── 计划任务 ───────────── */

/// 任务本身被禁用（与"触发器被禁用"是两件事）。
pub const TASK_DISABLED: &str = "TASK_DISABLED";

/// 任务的触发器被禁用，但任务本身仍是启用状态。
///
/// 这一条要单独存在，是因为两者的**恢复位置不同**：
/// 前者在任务计划程序的「常规」选项卡，后者在「触发器」选项卡。
/// 把它们混成一句话，用户会去错的地方找。
pub const TASK_TRIGGER_DISABLED: &str = "TASK_TRIGGER_DISABLED";

/// 一个任务挂了多个动作。
///
/// 这不是"问题"，是**防止误判**的说明：用户以为处理掉界面上显示的那个程序
/// 就完事了，实际上停用这个任务会连带影响其它几个程序。
/// 归在诊断里是因为它必须出现在用户做决定之前。
pub const MULTI_ACTION_TASK: &str = "MULTI_ACTION_TASK";
