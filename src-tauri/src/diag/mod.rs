//! 诊断引擎。
//!
//! 这一层回答的问题只有一个：**"这一项有没有问题？"**
//!
//! 扫描器负责"把系统里的记录读出来"（客观事实），
//! 诊断引擎负责"这些事实合在一起意味着什么"（判断）。
//! 分开的原因很实际：判断规则会反复调整，而读取逻辑相对稳定。
//! 把判断混进扫描器里，每改一次规则就要重测一遍所有读取路径。
//!
//! ## 子模块
//!
//! | 模块 | 职责 |
//! |---|---|
//! | `codes` | 诊断码的唯一产地 |
//! | `known` | 「本该是什么样」的参照表（白名单） |
//! | `boot_log` | 从事件日志读开机耗时原始数据 |
//! | `boot_record` | 「开机记录」开关的探测与一键开启（唯一写系统策略的模块） |
//! | `timeline` | 把事件数据拼成相位时间轴，并把慢服务对应到启动项 |
//! | `risk` | 三层风险评级 |
//!
//! ## 两条贯穿全层的原则
//!
//! **1. 证据优先。** 每条诊断都带 `evidence`（实际读到的数值）。
//! 用户应该能拿这个数值去系统里自己复核——这正是我们和"弹个警告说你
//! 电脑有问题"那类软件的区别。
//!
//! **2. 读不到就说读不到。** 事件日志需要管理员权限（实测普通用户
//! 对该 channel 没有任何 ACE），那就如实说明并给出提权入口，
//! 而不是返回一个看起来"开机耗时 0 秒"的空结构。空的和错的，
//! 对用户的伤害完全不是一个量级。

pub mod boot_log;
pub mod boot_marker;
pub mod boot_record;
pub mod boot_verdict;
pub mod codes;
pub mod known;
pub mod risk;
pub mod timeline;
